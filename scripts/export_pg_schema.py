"""Compile the SQLAlchemy metadata with the Postgres dialect.

Writes db/migrations/001_init.sql (applied by hand in the Supabase SQL editor) and db/schema.sql
(the current full schema; update it with every migration).

    poetry run python scripts/export_pg_schema.py
"""

from __future__ import annotations

from pathlib import Path

from onus.config import repo_root
from onus.db.models import postgres_ddl

HEADER = "-- Generated by scripts/export_pg_schema.py from onus.db.models. Do not edit by hand.\n\n"


def export(root: Path | None = None) -> list[Path]:
    root = root or repo_root()
    ddl = HEADER + postgres_ddl()
    out = [root / "db" / "migrations" / "001_init.sql", root / "db" / "schema.sql"]
    for p in out:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(ddl)
    return out


if __name__ == "__main__":
    for p in export():
        print(f"wrote {p}")
